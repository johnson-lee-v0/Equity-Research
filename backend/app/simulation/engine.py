    def replay(self, simulation_id: str) -> dict[str, Any] | None:
        with self.repository.db.operation() as conn:
            row = conn.execute("SELECT * FROM simulations s WHERE id=? AND NOT EXISTS (SELECT 1 FROM candidate_simulations cs WHERE cs.simulation_id=s.id)", (simulation_id,)).fetchone()
            if not row:
                return None
            events = conn.execute("SELECT * FROM simulation_events WHERE simulation_id=? ORDER BY round_no,rowid", (simulation_id,)).fetchall()
        if row["status"] != "completed":
            raise ValueError("simulation is incomplete and cannot be replayed")
        result = _safe_json(row["result_json"], {})
        if not isinstance(result, dict) or not result.get("rounds"):
            raise ValueError("completed simulation has no complete recorded rounds")

        mismatches: list[str] = []

        def replay_decimal(value: Any, default: Decimal, label: str) -> Decimal:
            try:
                return d(value)
            except (ValueError, TypeError):
                mismatches.append(f"{label}: invalid decimal")
                return default

        if not _hash_valid(result):
            mismatches.append("result integrity hash is invalid")
        initial_state = _safe_json(row["initial_state_json"], {})
        constraints = _safe_json(row["constraints_json"], {})
        shocks = _safe_json(row["shocks_json"], {})
        profiles = _safe_json(row["participants_json"], [])
        opening_profiles = _safe_json(initial_state.get("participant_profiles"), profiles) if isinstance(initial_state, dict) else profiles
        if not isinstance(opening_profiles, list):
            opening_profiles = profiles
        # participants_json is updated to final values at completion; replay
        # reconstructs opening balances from the immutable initial snapshot and
        # static profile fields from the result/row.
        result_participants = result.get("participants") if isinstance(result.get("participants"), list) else []
        profile_by_id = {str(item.get("id")): item for item in opening_profiles if isinstance(item, dict)}
        for item in result_participants:
            if isinstance(item, dict) and item.get("id") in profile_by_id:
                merged = profile_by_id[item["id"]]
                for key in ("horizon", "style", "information_mode", "information_set", "base_target_weight", "target_sensitivity", "adjustment_speed", "initial_cash", "initial_shares", "max_long_exposure", "max_exposure"):
                    if key in item:
                        merged[key] = item[key]
        snapshot_hash = digest({"initial_state": initial_state, "constraints": constraints, "shocks": shocks, "participants": opening_profiles})
        if result.get("initial_snapshot_hash") != snapshot_hash:
            mismatches.append("initial state/constraint/source snapshot hash is invalid")

        transitions = list(shocks.get("transitions") or []) if isinstance(shocks, dict) else []
        expected_round_count = int(row["rounds"])
        if len(transitions) != expected_round_count:
            mismatches.append("recorded price transition count is incomplete")
        if len(result.get("rounds", [])) != expected_round_count:
            mismatches.append("recorded result round count is incomplete")

        event_dicts = [
            {
                "round_no": int(event["round_no"]),
                "participant_id": event["participant_id"],
                "event_type": event["event_type"],
                "action": json_loads(event["action_json"], {}),
                "state": json_loads(event["state_json"], {}),
                "repair_attempt": json_loads(event["repair_attempt_json"], None),
                "recorded_response": json_loads(event["recorded_response_json"], None),
            }
            for event in events
        ]
        by_round: dict[int, list[dict[str, Any]]] = {}
        for event in event_dicts:
            if event["round_no"] > 0:
                if event["round_no"] > expected_round_count:
                    mismatches.append(f"unexpected event after round {expected_round_count}")
                if event["event_type"] not in {"price_transition", "action"}:
                    mismatches.append(f"round {event['round_no']}: unexpected event type {event['event_type']!r}")
                by_round.setdefault(event["round_no"], []).append(event)
            elif event["event_type"] != "provider_failure":
                mismatches.append("unexpected non-round event in completed simulation")
            else:
                mismatches.append("completed simulation contains a provider failure event")

        try:
            participants, counterparty = self._initial_ledger(opening_profiles, initial_state)
        except (ValueError, TypeError, KeyError):
            mismatches.append("initial ledger snapshot is invalid")
            participants = self._participants(len(opening_profiles)) if 6 <= len(opening_profiles) <= 12 else []
            counterparty = {"id": "external_market_counterparty", "cash": q(ZERO), "shares": q(ZERO), "initial_cash": q(ZERO), "initial_shares": q(ZERO)}
        initial_price_value = initial_state.get("initial_price", initial_state.get("price", ZERO)) if isinstance(initial_state, Mapping) else ZERO
        current_price = replay_decimal(initial_price_value, ZERO, "initial price")
        replay_rounds: list[dict[str, Any]] = []
        expected_ids = [item["id"] for item in participants]
        expected_model_response = None
        if isinstance(result.get("recorded_responses"), list) and result["recorded_responses"]:
            expected_model_response = result["recorded_responses"][0]

        for round_no in range(1, expected_round_count + 1):
            round_events = by_round.get(round_no, [])
            price_events = [item for item in round_events if item["event_type"] == "price_transition"]
            action_events = [item for item in round_events if item["event_type"] == "action"]
            if len(price_events) != 1:
                mismatches.append(f"round {round_no}: expected exactly one price transition")
                continue
            if len(action_events) != len(expected_ids):
                mismatches.append(f"round {round_no}: expected {len(expected_ids)} participant actions")
            if len({item["participant_id"] for item in action_events}) != len(action_events) or set(item["participant_id"] for item in action_events) != set(expected_ids):
                mismatches.append(f"round {round_no}: participant action set is incomplete or duplicated")

            price_event = price_events[0]
            transition = price_event["action"]
            if not _hash_valid(transition):
                mismatches.append(f"round {round_no}: price transition integrity hash is invalid")
            transition_body = _without_hash(transition) if isinstance(transition, dict) else {}
            price_before = replay_decimal(transition_body.get("price_before", current_price), current_price, f"round {round_no} price_before")
            price_after = replay_decimal(transition_body.get("price_after", ZERO), ZERO, f"round {round_no} price_after")
            if price_before != current_price:
                mismatches.append(f"round {round_no}: recorded price_before does not connect")
            if round_no == 1:
                expected_drift = replay_decimal(shocks.get("percent", "0") if isinstance(shocks, dict) else ZERO, ZERO, "declared shock")
                expected_mechanism = "declared_shock"
            else:
                # Replay consumes the recorded transition.  It deliberately
                # does not regenerate a path from the seed; the seed is an
                # input/audit label, while the persisted prices are the exact
                # replay inputs.
                expected_drift = replay_decimal(transition_body.get("drift_percent"), ZERO, f"round {round_no} recorded drift")
                expected_mechanism = "seeded_bounded_drift"
            if not _numeric_equal(transition_body.get("drift_fraction"), q(expected_drift / Decimal("100"))):
                mismatches.append(f"round {round_no}: recorded drift fraction is invalid")
            if not _numeric_equal(transition_body.get("drift_percent"), q(expected_drift)):
                mismatches.append(f"round {round_no}: recorded drift is not canonical")
            if round_no > 1 and abs(expected_drift) > MAX_DRIFT * Decimal("100"):
                mismatches.append(f"round {round_no}: recorded drift exceeds the bounded path limit")
            expected_shock = replay_decimal(shocks.get("percent", "0") if isinstance(shocks, dict) else ZERO, ZERO, "declared shock") if round_no == 1 else ZERO
            if not _numeric_equal(transition_body.get("shock_percent"), q(expected_shock)) or not _numeric_equal(transition_body.get("shock_fraction"), q(expected_shock / Decimal("100"))):
                mismatches.append(f"round {round_no}: recorded shock transition is invalid")
            if transition_body.get("mechanism") != expected_mechanism:
                mismatches.append(f"round {round_no}: price mechanism is invalid")
            recomputed_price = _quantize(price_before * (ONE + expected_drift / Decimal("100")), ROUND_HALF_UP)
            if recomputed_price != price_after or price_after <= ZERO:
                mismatches.append(f"round {round_no}: recorded price transition is invalid")
            if not _hash_valid(price_event["state"]):
                mismatches.append(f"round {round_no}: price state integrity hash is invalid")
            price_state_before_actions = self._ledger_snapshot(participants, counterparty, price_after)
            expected_price_state = {"stage": "price_transition", "round": round_no, "state": price_state_before_actions}
            _compare_values(price_event["state"], _with_hash(expected_price_state), f"round {round_no}.price_state", mismatches)

            round_result = result["rounds"][round_no - 1] if round_no - 1 < len(result["rounds"]) else {}
            if not isinstance(round_result, dict):
                round_result = {}
            state_before = self._ledger_snapshot(participants, counterparty, price_before)
            if "state_before" in round_result:
                _compare_values(round_result["state_before"], state_before, f"round {round_no}.state_before", mismatches)
            if not isinstance(round_result.get("actions"), list):
                mismatches.append(f"round {round_no}: result action list is missing")
            elif len(round_result["actions"]) != len(expected_ids) or {item.get("participant_id") for item in round_result["actions"] if isinstance(item, dict)} != set(expected_ids):
                mismatches.append(f"round {round_no}: result action set is incomplete or duplicated")
            replay_actions: list[dict[str, Any]] = []
            for action_event in sorted(action_events, key=lambda item: expected_ids.index(item["participant_id"]) if item["participant_id"] in expected_ids else len(expected_ids)):
                action = action_event["action"]
                if not _hash_valid(action):
                    mismatches.append(f"round {round_no} {action_event['participant_id']}: action integrity hash is invalid")
                action_body = _without_hash(action) if isinstance(action, dict) else {}
                participant = next((item for item in participants if item["id"] == action_event["participant_id"]), None)
                if participant is None:
                    mismatches.append(f"round {round_no}: action references an unknown participant")
                    continue
                action_name = action_body.get("action")
                quantity = replay_decimal(action_body.get("quantity", ZERO), ZERO, f"round {round_no} {participant['id']} quantity")
                trade_price = replay_decimal(action_body.get("price", price_after), price_after, f"round {round_no} {participant['id']} price")
                if trade_price != price_after:
                    mismatches.append(f"round {round_no} {participant['id']}: action price differs from round price")
                if quantity < ZERO or action_name not in ACTION_VALUES:
                    mismatches.append(f"round {round_no} {participant['id']}: action or quantity is invalid")
                    continue
                # Replay uses the recorded validated action and quantity.  It
                # does not call the provider and does not regenerate actions.
                before_cash = d(participant["cash"])
                before_shares = d(participant["shares"])
                cp_before_cash = d(counterparty["cash"])
                cp_before_shares = d(counterparty["shares"])
                if action_name == "hold":
                    if quantity != ZERO:
                        mismatches.append(f"round {round_no} {participant['id']}: hold has a non-zero quantity")
                elif action_name == "buy":
                    cost = _quantize(quantity * price_after, ROUND_HALF_UP)
                    if cost <= ZERO or cost > before_cash or quantity > cp_before_shares:
                        mismatches.append(f"round {round_no} {participant['id']}: recorded buy cannot settle")
                    else:
                        participant["cash"] = q(before_cash - cost)
                        participant["shares"] = q(before_shares + quantity)
                        counterparty["cash"] = q(cp_before_cash + cost)
                        counterparty["shares"] = q(cp_before_shares - quantity)
                else:
                    proceeds = _quantize(quantity * price_after, ROUND_HALF_UP)
                    if proceeds <= ZERO or quantity > before_shares or proceeds > cp_before_cash:
                        mismatches.append(f"round {round_no} {participant['id']}: recorded sell cannot settle")
                    else:
                        participant["cash"] = q(before_cash + proceeds)
                        participant["shares"] = q(before_shares - quantity)
                        counterparty["cash"] = q(cp_before_cash - proceeds)
                        counterparty["shares"] = q(cp_before_shares + quantity)
                self._refresh_participant(participant, price_after)
                # Target fields are part of the participant's recorded final
                # state even when the action is a hold/no-op.  Reapply them
                # from the validated action, just as the original run did.
                try:
                    participant["target_weight"] = q(replay_decimal(action_body.get("target_weight", participant.get("target_weight", ZERO)), ZERO, f"round {round_no} {participant['id']} target"))
                    participant["rules_target_weight"] = q(replay_decimal(action_body.get("rules_target_weight", participant.get("rules_target_weight", ZERO)), ZERO, f"round {round_no} {participant['id']} rules target"))
                except ValueError:
                    mismatches.append(f"round {round_no} {participant['id']}: recorded target is invalid")
                if d(participant["exposure"]) > MAX_LONG_EXPOSURE + Q:
                    mismatches.append(f"round {round_no} {participant['id']}: recorded action breaches maximum exposure")
                action_state = self._ledger_snapshot(participants, counterparty, price_after)
                expected_action_state = {
                    "stage": "action",
                    "round": round_no,
                    "participant_id": participant["id"],
                    "price": q(price_after),
                    "participant_exposure": participant["exposure"],
                    "state": action_state,
                }
                if not _hash_valid(action_event["state"]):
                    mismatches.append(f"round {round_no} {participant['id']}: action state integrity hash is invalid")
                _compare_values(action_event["state"], _with_hash(expected_action_state), f"round {round_no}.{participant['id']}.state", mismatches)
                _compare_values(action_event["repair_attempt"], action_body.get("repair"), f"round {round_no}.{participant['id']}.repair", mismatches)
                recorded_ids = set(expected_model_response.get("participant_ids", [])) if isinstance(expected_model_response, dict) else set()
                expected_response = expected_model_response if round_no == 1 and participant["id"] in recorded_ids else None
                _compare_values(action_event["recorded_response"], expected_response, f"round {round_no}.{participant['id']}.recorded_response", mismatches)
                replay_action = _with_hash(action_body)
                replay_actions.append(replay_action)
                if isinstance(round_result.get("actions"), list):
                    recorded_result_action = next((item for item in round_result["actions"] if isinstance(item, dict) and item.get("participant_id") == participant["id"]), None)
                    if recorded_result_action is None:
                        mismatches.append(f"round {round_no} {participant['id']}: result action is missing")
                    else:
                        _compare_values(recorded_result_action, action, f"round {round_no}.{participant['id']}.result_action", mismatches)

            state_after = self._ledger_snapshot(participants, counterparty, price_after)
            if "state_after" in round_result:
                _compare_values(round_result["state_after"], state_after, f"round {round_no}.state_after", mismatches)
            if "state" in round_result:
                _compare_values(round_result["state"], state_after, f"round {round_no}.state", mismatches)
            if round_result.get("price") is not None and not _numeric_equal(round_result.get("price"), q(price_after)):
                mismatches.append(f"round {round_no}: result price differs")
            if isinstance(round_result.get("price_transition"), dict):
                _compare_values(round_result["price_transition"], transition, f"round {round_no}.transition", mismatches)
            replay_rounds.append({"round": round_no, "price": q(price_after), "state_after": state_after, "actions": replay_actions})
            current_price = price_after

        final_state = self._ledger_snapshot(participants, counterparty, current_price)
        _compare_values(result.get("state"), final_state, "final_state", mismatches)
        if isinstance(result.get("participants"), list):
            _compare_values(result["participants"], self._final_participants(participants, current_price), "final_participants", mismatches)
        baseline = result.get("rules_only_baseline")
        if isinstance(baseline, dict) and baseline.get("integrity_hash") and not _hash_valid(baseline):
            mismatches.append("rules-only baseline integrity hash is invalid")

        replay_events = [
            {
                "round": item["round_no"],
                "participant_id": item["participant_id"],
                "event_type": item["event_type"],
                "action": item["action"],
                "state": item["state"],
                "repair_attempt": item["repair_attempt"],
                "recorded_response": item["recorded_response"],
            }
            for item in event_dicts
        ]
        return {
            "simulation_id": simulation_id,
            "matches": not mismatches,
            "replay": {
                "events": replay_events,
                "rounds": replay_rounds,
                "final_state": final_state,
                "mismatches": mismatches,
                "summary": "Exact replay reapplied recorded prices and validated actions from the initial ledger; no provider was called.",
            },
        }
