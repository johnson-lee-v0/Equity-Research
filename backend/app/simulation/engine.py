def d(value: Any) -> Decimal:
    """Parse a finite value without ever doing ledger arithmetic as float."""

    if isinstance(value, bool):
        raise ValueError("simulation decimal is invalid")
    try:
        number = Decimal(str(value).strip())
    except (InvalidOperation, ValueError, TypeError, AttributeError):
        raise ValueError("simulation decimal is invalid")
    if not number.is_finite():
        raise ValueError("simulation decimal must be finite")
    return number


def q(value: Decimal) -> str:
    """Canonical persisted Decimal representation."""

    return format(_quantize(value, ROUND_HALF_UP), "f")


def _quantize(value: Decimal, rounding: str) -> Decimal:
    number = d(value)
    # Decimal's default context precision is intentionally small.  Expand it
    # for the bounded ledger value being quantized so a valid, finite input is
    # not rejected merely because it has more than 28 significant digits.
    exponent = number.as_tuple().exponent
    magnitude = abs(int(exponent)) if isinstance(exponent, int) else 0
    precision = max(28, len(number.as_tuple().digits) + magnitude + 20)
    with localcontext() as context:
        context.prec = precision
        return number.quantize(Q, rounding=rounding)


def _q_down(value: Decimal) -> Decimal:
    return _quantize(value, ROUND_DOWN)


def _q_up(value: Decimal) -> Decimal:
    return _quantize(value, ROUND_UP)


def _field(body: Any, name: str, default: Any = None) -> Any:
    if isinstance(body, Mapping):
        return body.get(name, default)
    return getattr(body, name, default)


def _safe_json(value: Any, default: Any) -> Any:
    if isinstance(value, (dict, list, tuple, int, float, bool)) or value is None:
        return value if value is not None else default
    return json_loads(value, default)


def _copy(value: Any) -> Any:
    return copy.deepcopy(value)


def _retain_structured_response(value: Any) -> Any:
    """Retain the structured artifact without persisting internal thoughts."""

    if isinstance(value, dict):
        return {
            key: _retain_structured_response(item)
            for key, item in value.items()
            if str(key).casefold() not in PRIVATE_RESPONSE_KEYS
        }
    if isinstance(value, list):
        return [_retain_structured_response(item) for item in value]
    return value


def _without_hash(value: Any) -> Any:
    if isinstance(value, dict):
        # Only remove the hash belonging to this record.  Nested state/action
        # records have their own integrity hashes and are part of the parent
        # result hash.
        return {key: item for key, item in value.items() if key != "integrity_hash"}
    return value


def _with_hash(value: dict[str, Any]) -> dict[str, Any]:
    result = _copy(value)
    result["integrity_hash"] = digest(result)
    return result


def _hash_valid(value: Any) -> bool:
    return isinstance(value, dict) and isinstance(value.get("integrity_hash"), str) and value["integrity_hash"] == digest(_without_hash(value))


def _normalise_model_config(value: Any) -> ModelConfig:
    if isinstance(value, ModelConfig):
        return value
    if isinstance(value, Mapping):
        return ModelConfig.model_validate(dict(value))
    raise ValueError("A07 model policy did not resolve to a valid model configuration")


def _numeric_equal(left: Any, right: Any) -> bool:
    """Compare numeric strings as Decimal while retaining strict metadata."""

    if isinstance(left, bool) or isinstance(right, bool):
        return left == right
    if isinstance(left, (int, float, Decimal)) and isinstance(right, (int, float, Decimal)):
        try:
            return d(left) == d(right)
        except ValueError:
            return left == right
    if isinstance(left, str) and isinstance(right, str):
        try:
            return d(left) == d(right)
        except ValueError:
            return left == right
    return left == right


def _compare_values(actual: Any, expected: Any, path: str, mismatches: list[str], *, limit: int = 80) -> None:
    """Recursively compare a replayed state with a recorded state."""

    if len(mismatches) >= limit:
        return
    if isinstance(actual, dict) and isinstance(expected, dict):
        actual_keys = set(actual)
        expected_keys = set(expected)
        for key in sorted(actual_keys - expected_keys):
            mismatches.append(f"{path}.{key}: unexpected recorded field")
        for key in sorted(expected_keys - actual_keys):
            mismatches.append(f"{path}.{key}: missing recorded field")
        for key in sorted(actual_keys & expected_keys):
            _compare_values(actual[key], expected[key], f"{path}.{key}", mismatches, limit=limit)
        return
    if isinstance(actual, list) and isinstance(expected, list):
        if len(actual) != len(expected):
            mismatches.append(f"{path}: list length {len(actual)} != {len(expected)}")
            return
        for index, (a_item, e_item) in enumerate(zip(actual, expected)):
            _compare_values(a_item, e_item, f"{path}[{index}]", mismatches, limit=limit)
        return
    if not _numeric_equal(actual, expected):
        mismatches.append(f"{path}: {actual!r} != {expected!r}")


def _participant_information(profile: Mapping[str, str]) -> list[str]:
    if profile["information_mode"] == "shock_informed":
        return [
            "declared_initial_price",
            "declared_shock",
            "current_exogenous_price",
            "round_one_shock_visible",
            f"style_signal:{profile['style']}",
        ]
    return [
        "declared_initial_price",
        "prior_round_price",
        "delayed_price",
        "round_one_shock_not_visible_until_next_round",
        f"style_signal:{profile['style']}",
    ]


class SimulationService:
    """Public simulation service preserving ``create/run/get/list/replay``."""

    def __init__(self, repository: Any, providers: Any = None):
        self.repository = repository
        # A provider registry is intentionally lazy: rules-only runs stay
        # disconnected, and tests can inject a fake without constructing the
        # real Codex/Ollama adapters.
        self.providers = providers

    def recover(self) -> int:
        """Close simulations left running by a process restart.

        A restarted process never replays or silently resumes a provider
        generation.  The next user action can create a new idempotent
        scenario, while this record remains an explicit interruption.
        """
        recovered = 0
        with self.repository.db.transaction(immediate=True) as conn:
            rows = conn.execute("SELECT id,name,seed FROM simulations s WHERE status='running' AND NOT EXISTS (SELECT 1 FROM candidate_simulations cs WHERE cs.simulation_id=s.id)").fetchall()
            for row in rows:
                result = {
                    "summary": "Hypothetical simulation was interrupted by backend restart; no result was replayed.",
                    "failure": {"status": "failed", "code": "interrupted", "reason": "Backend restarted while the simulation was running."},
                    "versions": {"code": SIMULATION_CODE_VERSION, "schema": SIMULATION_SCHEMA_VERSION, "seed": int(row["seed"])},
                }
                result["integrity_hash"] = digest(result)
                now = utc_now()
                updated = conn.execute("UPDATE simulations SET status='failed',result_json=?,finished_at=? WHERE id=? AND status='running'", (json_dumps(result), now, row["id"]))
                if updated.rowcount:
                    recovered += 1
                    self.repository.db.emit(conn, namespace="simulation", event_type="failed", payload={"simulation_id": row["id"], "agent_id": "A07", "failure_code": "interrupted", "message": "Running simulation was closed after backend restart."})
        return recovered

    # ------------------------------------------------------------------
    # Input and source snapshots
    # ------------------------------------------------------------------

    @staticmethod
    def _validate_inputs(body: Any) -> tuple[str, str, str, int, int, int, Decimal, Decimal, list[str], bool]:
        title = _field(body, "title")
        question = _field(body, "question")
        horizon = _field(body, "horizon")
        if not isinstance(title, str) or not title.strip():
            raise ValueError("title is required")
        if not isinstance(question, str) or not question.strip():
            raise ValueError("question is required")
        if not isinstance(horizon, str) or not horizon.strip():
            raise ValueError("horizon is required")

        participants = _field(body, "participants")
        rounds = _field(body, "rounds")
        seed = _field(body, "seed")
        if isinstance(participants, bool) or not isinstance(participants, int) or not 6 <= participants <= 12:
            raise ValueError("participants must be between 6 and 12")
        if isinstance(rounds, bool) or not isinstance(rounds, int) or not 5 <= rounds <= 10:
            raise ValueError("rounds must be between 5 and 10")
        if isinstance(seed, bool) or not isinstance(seed, int) or not 0 <= seed <= 2**63 - 1:
            raise ValueError("seed must be a non-negative integer")

        price = d(_field(body, "initial_price"))
        shock = d(_field(body, "shock_percent"))
        if price <= ZERO:
            raise ValueError("initial_price must be positive")
        if shock <= Decimal("-100"):
            raise ValueError("shock_percent must be greater than -100")

        raw_source_ids = _field(body, "source_ids", [])
        if raw_source_ids is None:
            raw_source_ids = []
        if not isinstance(raw_source_ids, (list, tuple)):
            raise ValueError("source_ids must be a list")
        source_ids = [str(item) for item in raw_source_ids]
        if any(not item.strip() for item in source_ids):
            raise ValueError("source_ids cannot contain an empty source ID")
        if len(set(source_ids)) != len(source_ids):
            raise ValueError("source_ids cannot contain duplicates")
        use_llm = _field(body, "use_llm", False)
        if not isinstance(use_llm, bool):
            raise ValueError("use_llm must be boolean")
        return title.strip(), question.strip(), horizon.strip(), participants, rounds, seed, price, shock, source_ids, use_llm

    @staticmethod
    def _source_snapshots(conn: Any, source_ids: list[str]) -> tuple[str | None, list[dict[str, Any]]]:
        if not source_ids:
            return None, []
        snapshots: list[dict[str, Any]] = []
        namespaces: set[str] = set()
        missing: list[str] = []
        for source_id in source_ids:
            row = conn.execute("SELECT * FROM sources WHERE id=?", (source_id,)).fetchone()
            if not row:
                missing.append(source_id)
                continue
            namespace = str(row["namespace"])
            if namespace == "simulation":
                raise ValueError("simulation sources cannot be used by a simulation")
            if namespace not in {"real", "demo"}:
                raise ValueError(f"source {source_id} has an unsupported namespace")
            namespaces.add(namespace)
            version_row = conn.execute("SELECT * FROM source_versions WHERE source_id=? ORDER BY version_no DESC LIMIT 1", (source_id,)).fetchone()
            version = int(version_row["version_no"]) if version_row else 1
            content = (version_row["content"] if version_row and version_row["content"] is not None else row["original_content"]) or ""
            content_hash = (version_row["content_hash"] if version_row and version_row["content_hash"] else row["content_hash"]) or ""
            snapshots.append(
                {
                    "id": source_id,
                    "source_id": source_id,
                    "namespace": namespace,
                    "title": row["title"],
                    "url": row["url"],
                    "publisher": row["publisher"],
                    "publication_at": row["publication_at"],
                    "observed_at": row["observed_at"] if "observed_at" in row.keys() else None,
                    "retrieved_at": row["retrieval_at"],
                    "version": version,
                    "content_hash": str(content_hash),
                    "locator": row["locator"],
                    "content": str(content),
                }
            )
        if missing:
            raise ValueError("source IDs are missing: " + ", ".join(missing))
        if len(namespaces) > 1:
            raise ValueError("source_ids must use one source namespace: real or demo; mixed namespaces are rejected")
        return (next(iter(namespaces)) if namespaces else None), snapshots

    @staticmethod
    def _participants(count: int) -> list[dict[str, Any]]:
        result: list[dict[str, Any]] = []
        for index in range(count):
            template = PROFILE_TEMPLATES[index]
            information_mode = template["information_mode"]
            result.append(
                {
                    "id": f"p{index + 1:02d}",
                    "horizon": template["horizon"],
                    "style": template["style"],
                    "information_mode": information_mode,
                    "information_set": _participant_information(template),
                    "base_target_weight": template["base_target"],
                    "target_weight": template["base_target"],
                    "rules_target_weight": template["base_target"],
                    "target_sensitivity": template["sensitivity"],
                    "adjustment_speed": template["adjustment_speed"],
                    "initial_cash": q(INITIAL_CASH),
                    "initial_shares": q(ZERO),
                    "cash": q(INITIAL_CASH),
                    "shares": q(ZERO),
                    "nav": q(INITIAL_CASH),
                    "exposure": q(ZERO),
                    "max_long_exposure": q(MAX_LONG_EXPOSURE),
                    "max_exposure": q(MAX_LONG_EXPOSURE),
                }
            )
        return result

    @staticmethod
    def _price_path(initial_price: Decimal, shock: Decimal, rounds: int, seed: int) -> list[dict[str, Any]]:
        rng = random.Random(seed)
        price = _quantize(initial_price, ROUND_HALF_UP)
        transitions: list[dict[str, str]] = []
        for round_no in range(1, rounds + 1):
            before = price
            if round_no == 1:
                drift = shock / Decimal("100")
                mechanism = "declared_shock"
                shock_value = shock
            else:
                drift = rng.choice(DRIFT_CHOICES)
                mechanism = "seeded_bounded_drift"
                shock_value = ZERO
            price = _quantize(price * (ONE + drift), ROUND_HALF_UP)
            if price <= ZERO:
                raise ValueError("declared shock produced a non-positive simulation price")
            transitions.append(
                {
                    "round": round_no,
                    "price_before": q(before),
                    "price_after": q(price),
                    "drift_fraction": q(drift),
                    "drift_percent": q(drift * Decimal("100")),
                    "shock_fraction": q(shock_value / Decimal("100")),
                    "shock_percent": q(shock_value),
                    "mechanism": mechanism,
                    "bounded": round_no > 1,
                }
            )
        return transitions

    def create(self, body: Any) -> dict[str, Any]:
        title, question, horizon, participants_count, rounds_count, seed, price, shock, source_ids, use_llm = self._validate_inputs(body)
        idempotency_key = _field(body, "idempotency_key")
        if not isinstance(idempotency_key, str) or not idempotency_key.strip():
            raise ValueError("idempotency_key is required")
        idempotency_key = idempotency_key.strip()
        transitions = self._price_path(price, shock, rounds_count, seed)

        with self.repository.db.transaction(immediate=True) as conn:
            existing = conn.execute("SELECT id,status,name,horizon,rounds,seed,initial_state_json,shocks_json FROM simulations WHERE idempotency_key=?", (idempotency_key,)).fetchone()
            if existing:
                prior_initial = json_loads(existing["initial_state_json"], {})
                prior_shocks = json_loads(existing["shocks_json"], {})
                prior_sources = prior_initial.get("source_ids", []) if isinstance(prior_initial, dict) else []
                prior_use_llm = bool(prior_initial.get("use_llm")) if isinstance(prior_initial, dict) else False
                if (
                    existing["name"] != title
                    or existing["horizon"] != horizon
                    or int(existing["rounds"]) != rounds_count
                    or int(existing["seed"]) != seed
                    or prior_initial.get("initial_price", prior_initial.get("price")) != q(price)
                    or prior_shocks.get("percent") != q(shock)
                    or prior_shocks.get("question") != question
                    or list(prior_sources) != source_ids
                    or prior_use_llm != use_llm
                ):
                    raise ValueError("idempotency_key is already used by a different simulation request")
                return {"simulation_id": existing["id"], "status": existing["status"], "reused": True}

            source_namespace, source_snapshots = self._source_snapshots(conn, source_ids)
            participants = self._participants(participants_count)
            minimum_price = min([price, *[d(item["price_after"]) for item in transitions]])
            total_participant_cash = INITIAL_CASH * participants_count
            # The counterparty is explicit inventory, not an unlimited hidden
            # pool.  It is deliberately over-reserved so every valid bounded
            # long trade can settle without making cash/shares negative.
            counterparty = {
                "id": "external_market_counterparty",
                "cash": q(total_participant_cash * Decimal("2")),
                "shares": q(_q_up(total_participant_cash * Decimal("2") / minimum_price)),
                "initial_cash": q(total_participant_cash * Decimal("2")),
                "initial_shares": q(_q_up(total_participant_cash * Decimal("2") / minimum_price)),
            }
            initial_participants = [
                {
                    "id": item["id"],
                    "cash": item["cash"],
                    "shares": item["shares"],
                    "nav": item["nav"],
                    "exposure": item["exposure"],
                    "target_weight": item["target_weight"],
                }
                for item in participants
            ]
            initial_state: dict[str, Any] = {
                "price": q(price),
                "initial_price": q(price),
                "cash": q(INITIAL_CASH),  # compatibility alias for the per-participant opening cash
                "shares": q(ZERO),
                "nav": q(INITIAL_CASH),
                "exposure": q(ZERO),
                "participant_cash_total": q(total_participant_cash),
                "aggregate_cash": q(total_participant_cash + d(counterparty["cash"])),
                "aggregate_shares": q(d(counterparty["shares"])),
                "shock_percent": q(shock),
                "participants": initial_participants,
                "participant_initial_states": initial_participants,
                "participant_states": initial_participants,
                # Keep the complete immutable profile definition here.  The
                # top-level participants column is updated with final values,
                # while replay still needs the opening rules and speeds.
                "participant_profiles": _copy(participants),
                "external_market_counterparty": counterparty,
                "source_namespace": source_namespace,
                "source_ids": list(source_ids),
                "source_snapshots": source_snapshots,
                # Short aliases make the retained source lineage easy to
                # inspect while keeping the explicit snapshot name canonical.
                "sources": _copy(source_snapshots),
                "source_versions": {
                    item["id"]: {
                        "namespace": item["namespace"],
                        "version": item["version"],
                        "content_hash": item["content_hash"],
                        "locator": item["locator"],
                        "content": item["content"],
                    }
                    for item in source_snapshots
                },
                "use_llm": use_llm,
            }
            constraints: dict[str, Any] = {
                "max_participant_exposure": q(MAX_LONG_EXPOSURE),
                "max_long_exposure": q(MAX_LONG_EXPOSURE),
                "min_cash": q(ZERO),
                "min_shares": q(ZERO),
                "actions": sorted(ACTION_VALUES),
                "ledger_quantum": q(Q),
                "market_counterparty": "external_market_counterparty",
                "price_path": "exogenous_only",
            }
            shocks: dict[str, Any] = {
                "percent": q(shock),
                "question": question,
                "first_round": "declared_shock",
                "subsequent_rounds": "seeded_bounded_drift",
                "max_drift_percent": q(MAX_DRIFT * Decimal("100")),
                "transitions": transitions,
            }
            simulation_id = new_id("sim_")
            now = utc_now()
            conn.execute(
                "INSERT INTO simulations(id,idempotency_key,namespace,name,horizon,participants_json,initial_state_json,constraints_json,shocks_json,rounds,seed,provider,model,status,created_at) VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)",
                (
                    simulation_id,
                    idempotency_key,
                    "simulation",
                    title,
                    horizon,
                    json_dumps(participants),
                    json_dumps(initial_state),
                    json_dumps(constraints),
                    json_dumps(shocks),
                    rounds_count,
                    seed,
                    "configured" if use_llm else "rules",
                    None,
                    "queued",
                    now,
                ),
            )
            self.repository.db.emit(
                conn,
                namespace="simulation",
                event_type="queued",
                payload={"simulation_id": simulation_id, "agent_id": "A07", "message": "Bounded simulation queued; the price path is exogenous and hypothetical."},
            )
        return {"simulation_id": simulation_id, "status": "queued", "reused": False}

