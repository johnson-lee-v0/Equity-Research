    # Ledger and rules
    # ------------------------------------------------------------------

    @staticmethod
    def _initial_ledger(profiles: list[dict[str, Any]], initial_state: Mapping[str, Any]) -> tuple[list[dict[str, Any]], dict[str, Any]]:
        initial_rows = initial_state.get("participant_initial_states") or initial_state.get("participants") or []
        by_id = {str(item.get("id")): item for item in initial_rows if isinstance(item, dict)}
        participants = _copy(profiles)
        for participant in participants:
            opening = by_id.get(participant["id"], {})
            participant["cash"] = q(d(opening.get("cash", participant.get("initial_cash", INITIAL_CASH))))
            participant["shares"] = q(d(opening.get("shares", participant.get("initial_shares", ZERO))))
            participant["target_weight"] = q(d(opening.get("target_weight", participant.get("target_weight", ZERO))))
            participant["rules_target_weight"] = q(d(opening.get("target_weight", participant.get("rules_target_weight", ZERO))))
            participant["nav"] = q(d(opening.get("nav", participant.get("cash", INITIAL_CASH))))
            participant["exposure"] = q(d(opening.get("exposure", ZERO)))
        counterparty = _copy(initial_state.get("external_market_counterparty") or {})
        counterparty.setdefault("id", "external_market_counterparty")
        counterparty["cash"] = q(d(counterparty.get("cash", ZERO)))
        counterparty["shares"] = q(d(counterparty.get("shares", ZERO)))
        counterparty["initial_cash"] = q(d(counterparty.get("initial_cash", counterparty["cash"])))
        counterparty["initial_shares"] = q(d(counterparty.get("initial_shares", counterparty["shares"])))
        return participants, counterparty

    @staticmethod
    def _refresh_participant(participant: dict[str, Any], price: Decimal) -> None:
        cash = d(participant.get("cash", ZERO))
        shares = d(participant.get("shares", ZERO))
        if cash < ZERO or shares < ZERO:
            raise ValueError("simulation ledger attempted a negative cash or share balance")
        stock_value = _quantize(shares * price, ROUND_HALF_UP)
        nav = _quantize(cash + stock_value, ROUND_HALF_UP)
        exposure = _quantize(stock_value / nav, ROUND_HALF_UP) if nav > ZERO else ZERO
        participant["cash"] = q(cash)
        participant["shares"] = q(shares)
        participant["stock_value"] = q(stock_value)
        participant["nav"] = q(nav)
        participant["exposure"] = q(exposure)

    @classmethod
    def _ledger_snapshot(cls, participants: list[dict[str, Any]], counterparty: dict[str, Any], price: Decimal) -> dict[str, Any]:
        for participant in participants:
            cls._refresh_participant(participant, price)
        cp_cash = d(counterparty.get("cash", ZERO))
        cp_shares = d(counterparty.get("shares", ZERO))
        if cp_cash < ZERO or cp_shares < ZERO:
            raise ValueError("simulation counterparty attempted a negative balance")
        participant_states = [
            {
                "participant_id": item["id"],
                "cash": item["cash"],
                "shares": item["shares"],
                "stock_value": item["stock_value"],
                "nav": item["nav"],
                "exposure": item["exposure"],
            }
            for item in participants
        ]
        total_cash = sum((d(item["cash"]) for item in participants), ZERO) + cp_cash
        total_shares = sum((d(item["shares"]) for item in participants), ZERO) + cp_shares
        participant_wealth = sum((d(item["nav"]) for item in participants), ZERO)
        participant_cash = sum((d(item["cash"]) for item in participants), ZERO)
        participant_shares = sum((d(item["shares"]) for item in participants), ZERO)
        participant_exposure = sum((d(item["exposure"]) for item in participants), ZERO)
        marked_wealth = participant_wealth + cp_cash + (cp_shares * price)
        return {
            "price": q(price),
            "participants": participant_states,
            "external_market_counterparty": {"id": counterparty["id"], "cash": q(cp_cash), "shares": q(cp_shares)},
            "total_cash": q(total_cash),
            "total_shares": q(total_shares),
            # Compatibility aliases for the original compact state shape.
            "cash": q(participant_cash),
            "shares": q(participant_shares),
            "exposure": q(participant_exposure),
            "participant_marked_to_market_wealth": q(participant_wealth),
            "marked_to_market_wealth": q(marked_wealth),
        }

    @staticmethod
    def _target_weight(participant: Mapping[str, Any], *, round_no: int, price_before: Decimal, price_after: Decimal, initial_price: Decimal) -> Decimal:
        mode = participant.get("information_mode")
        observed = price_after if mode == "shock_informed" else price_before
        move = (observed / initial_price) - ONE
        base = d(participant.get("base_target_weight", participant.get("target_weight", ZERO)))
        sensitivity = d(participant.get("target_sensitivity", ZERO))
        # A delayed participant intentionally sees no first-round price move;
        # subsequent rounds use the previous recorded price.  The round number
        # remains part of the rule so the distinction is explicit in audit data.
        if round_no == 1 and mode == "delayed_price":
            move = ZERO
        return max(ZERO, min(MAX_LONG_EXPOSURE, base + (sensitivity * move)))

    @staticmethod
    def _requested_quantity(participant: Mapping[str, Any], target_weight: Decimal, price: Decimal) -> tuple[str, Decimal]:
        cash = d(participant.get("cash", ZERO))
        shares = d(participant.get("shares", ZERO))
        nav = _quantize(cash + shares * price, ROUND_HALF_UP)
        target_shares = _quantize(nav * target_weight / price, ROUND_HALF_UP) if price > ZERO else ZERO
        gap = target_shares - shares
        speed = max(ZERO, min(ONE, d(participant.get("adjustment_speed", ZERO))))
        if gap.copy_abs() < Q:
            return "hold", ZERO
        quantity = _q_down(gap.copy_abs() * speed)
        if quantity <= ZERO:
            return "hold", ZERO
        return ("buy" if gap > ZERO else "sell"), quantity

    @classmethod
    def _execute_trade(
        cls,
        participant: dict[str, Any],
        counterparty: dict[str, Any],
        requested_action: str,
        requested_quantity: Decimal,
        price: Decimal,
        target_weight: Decimal,
        *,
        repair: dict[str, Any] | None = None,
    ) -> tuple[str, Decimal, Decimal, dict[str, Any] | None]:
        """Apply one fully numeric trade or a deterministic no-op repair."""

        if requested_action not in ACTION_VALUES:
            repair = repair or {"reason": "unsupported action", "deterministic": True}
            return "hold", ZERO, ZERO, repair
        quantity = _q_down(requested_quantity)
        if requested_action == "hold" or quantity <= ZERO:
            return "hold", ZERO, ZERO, repair

        cash = d(participant["cash"])
        shares = d(participant["shares"])
        cp_cash = d(counterparty["cash"])
        cp_shares = d(counterparty["shares"])
        if requested_action == "buy":
            cost = _quantize(quantity * price, ROUND_HALF_UP)
            # A provider cannot cause a partial or reserve-creating fill.  If
            # the bounded request cannot settle, the deterministic result is a
            # no-op, which is recorded by the caller.
            if cost <= ZERO or cost > cash or quantity > cp_shares:
                repair = repair or {"reason": "buy cannot settle without negative cash or counterparty shares", "deterministic": True}
                return "hold", ZERO, ZERO, repair
            participant["cash"] = q(cash - cost)
            participant["shares"] = q(shares + quantity)
            counterparty["cash"] = q(cp_cash + cost)
            counterparty["shares"] = q(cp_shares - quantity)
            return "buy", quantity, cost, repair

        proceeds = _quantize(quantity * price, ROUND_HALF_UP)
        if proceeds <= ZERO or quantity > shares or proceeds > cp_cash:
            repair = repair or {"reason": "sell cannot settle without negative shares or counterparty cash", "deterministic": True}
            return "hold", ZERO, ZERO, repair
        participant["cash"] = q(cash + proceeds)
        participant["shares"] = q(shares - quantity)
        counterparty["cash"] = q(cp_cash - proceeds)
        counterparty["shares"] = q(cp_shares + quantity)
        return "sell", quantity, proceeds, repair

    @classmethod
    def _run_action(
        cls,
        participant: dict[str, Any],
        counterparty: dict[str, Any],
        price: Decimal,
        rules_target: Decimal,
        model_decision: dict[str, Any] | None,
    ) -> dict[str, Any]:
        cls._refresh_participant(participant, price)
        max_exposure = min(MAX_LONG_EXPOSURE, d(participant.get("max_long_exposure", MAX_LONG_EXPOSURE)))
        current_exposure = d(participant["exposure"])
        target = rules_target
        target_source = "rules"
        requested_action: Any
        requested_quantity: Decimal
        repair: dict[str, Any] | None = None

        if model_decision is not None and model_decision.get("valid"):
            target = d(model_decision["target_weight"])
            target_source = "model_bounded_target"
            if model_decision.get("target_only"):
                # The single model action is a round-one suggestion.  Its
                # bounded target may persist, but later adjustment speed and
                # trade direction are always determined by backend rules.
                requested_action, requested_quantity = cls._requested_quantity(participant, target, price)
            else:
                requested_action = model_decision["action"]
                if requested_action == "hold":
                    requested_quantity = ZERO
                else:
                    computed_action, computed_quantity = cls._requested_quantity(participant, target, price)
                    if computed_action != requested_action:
                        repair = {
                            "reason": "model action conflicts with its bounded target and current ledger",
                            "requested_action": requested_action,
                            "applied_action": "hold",
                            "applied_quantity": q(ZERO),
                            "deterministic": True,
                        }
                        requested_action = "hold"
                        requested_quantity = ZERO
                    else:
                        requested_quantity = computed_quantity
        elif model_decision is not None:
            # An invalid provider action must not silently become a rules
            # action.  It is an auditable deterministic no-op.
            requested_action = "hold"
            requested_quantity = ZERO
            repair = _copy(model_decision.get("repair"))
            target_source = "invalid_model_noop"
        else:
            requested_action, requested_quantity = cls._requested_quantity(participant, target, price)

        # A price move can push a previously valid holding over the hard cap.
        # Deterministic risk enforcement takes precedence over a model hold or
        # buy request, and sells only the excess.
        if current_exposure > max_exposure:
            nav = d(participant["nav"])
            allowed_shares = _q_down(nav * max_exposure / price)
            excess = d(participant["shares"]) - allowed_shares
            if excess > ZERO:
                requested_action = "sell"
                requested_quantity = excess
                repair = {
                    "reason": "maximum long exposure enforced",
                    "requested_action": model_decision.get("action") if model_decision else requested_action,
                    "applied_action": "sell",
                    "deterministic": True,
                }

        applied_action, quantity, trade_value, repair = cls._execute_trade(
            participant,
            counterparty,
            requested_action,
            requested_quantity,
            price,
            target,
            repair=repair,
        )
        cls._refresh_participant(participant, price)
        if d(participant["exposure"]) > max_exposure + Q:
            # This should only be reachable when a counterparty reserve is
            # externally tampered with.  Keep the state safe and make the
            # anomaly visible as a no-op repair rather than persisting a
            # violating trade.
            raise ValueError("simulation ledger exceeded the participant exposure limit")
        participant["target_weight"] = q(target)
        participant["rules_target_weight"] = q(rules_target)
        action_record: dict[str, Any] = {
            "participant_id": participant["id"],
            "action": applied_action,
            "requested_action": requested_action,
            "quantity": q(quantity),
            "price": q(price),
            "trade_value": q(trade_value),
            "target_weight": q(target),
            "rules_target_weight": q(rules_target),
            "target_source": target_source,
            "adjustment_speed": q(d(participant.get("adjustment_speed", ZERO))),
            "cash_after": participant["cash"],
            "shares_after": participant["shares"],
            "nav_after": participant["nav"],
            "exposure_after": participant["exposure"],
            "counterparty_cash_after": q(d(counterparty["cash"])),
            "counterparty_shares_after": q(d(counterparty["shares"])),
            "repair": repair,
            "repair_attempt": repair,
            "validated": True,
        }
        return _with_hash(action_record)

    @classmethod
    def _final_participants(cls, participants: list[dict[str, Any]], price: Decimal) -> list[dict[str, Any]]:
        output: list[dict[str, Any]] = []
        for participant in participants:
            cls._refresh_participant(participant, price)
            output.append(
                {
                    "id": participant["id"],
                    "horizon": participant["horizon"],
                    "style": participant["style"],
                    "information_mode": participant["information_mode"],
                    "information_set": _copy(participant["information_set"]),
                    "initial_cash": participant["initial_cash"],
                    "initial_shares": participant["initial_shares"],
                    "cash": participant["cash"],
                    "shares": participant["shares"],
                    "nav": participant["nav"],
                    "exposure": participant["exposure"],
                    "target_weight": participant.get("target_weight", participant.get("base_target_weight", q(ZERO))),
                    "rules_target_weight": participant.get("rules_target_weight", participant.get("base_target_weight", q(ZERO))),
                    "base_target_weight": participant.get("base_target_weight", q(ZERO)),
                    "target_sensitivity": participant.get("target_sensitivity", q(ZERO)),
                    "max_long_exposure": participant["max_long_exposure"],
                    "max_exposure": participant["max_exposure"],
                    "adjustment_speed": participant["adjustment_speed"],
                }
            )
        return output

    @classmethod
    def _simulate_path(
        cls,
        profiles: list[dict[str, Any]],
        initial_state: Mapping[str, Any],
        transitions: list[dict[str, Any]],
        *,
        model_decisions: Mapping[str, dict[str, Any]] | None = None,
        response_record: dict[str, Any] | None = None,
        record_events: bool,
    ) -> dict[str, Any]:
        participants, counterparty = cls._initial_ledger(profiles, initial_state)
        initial_price = d(initial_state.get("initial_price", initial_state.get("price", ZERO)))
        rounds: list[dict[str, Any]] = []
        event_specs: list[dict[str, Any]] = []
        previous_price = initial_price

        for transition in transitions:
            round_no = int(transition["round"])
            price_before = d(transition["price_before"])
            price_after = d(transition["price_after"])
            if price_before != previous_price:
                raise ValueError("simulation transition does not connect to the previous price")
            state_before = cls._ledger_snapshot(participants, counterparty, price_before)
            transition_record = _with_hash(
                {
                    "round": round_no,
                    "price_before": q(price_before),
                    "price_after": q(price_after),
                    "drift_fraction": transition.get("drift_fraction", q(d(transition["drift_percent"]) / Decimal("100"))),
                    "drift_percent": transition["drift_percent"],
                    "shock_fraction": transition.get("shock_fraction", q(d(transition["shock_percent"]) / Decimal("100"))),
                    "shock_percent": transition["shock_percent"],
                    "mechanism": transition["mechanism"],
                    "bounded": transition["bounded"],
                }
            )
            state_after_price = cls._ledger_snapshot(participants, counterparty, price_after)
            price_state = _with_hash({"stage": "price_transition", "round": round_no, "state": state_after_price})
            if record_events:
                event_specs.append(
                    {
                        "round_no": round_no,
                        "participant_id": None,
                        "event_type": "price_transition",
                        "action": transition_record,
                        "state": price_state,
                        "repair": None,
                        "recorded_response": None,
                    }
                )

            actions: list[dict[str, Any]] = []
            for participant in participants:
                rules_target = cls._target_weight(
                    participant,
                    round_no=round_no,
                    price_before=price_before,
                    price_after=price_after,
                    initial_price=initial_price,
                )
                decision = None
                if model_decisions and participant["id"] in model_decisions:
                    decision = model_decisions[participant["id"]]
                if round_no > 1 and decision and decision.get("valid"):
                    decision = {"valid": True, "target_only": True, "target_weight": decision["target_weight"]}
                action = cls._run_action(participant, counterparty, price_after, rules_target, decision)
                actions.append(action)
                action_state = _with_hash(
                    {
                        "stage": "action",
                        "round": round_no,
                        "participant_id": participant["id"],
                        "price": q(price_after),
                        "participant_exposure": participant["exposure"],
                        "state": cls._ledger_snapshot(participants, counterparty, price_after),
                    }
                )
                repair = action.get("repair")
                recorded_ids = set(response_record.get("participant_ids", [])) if response_record else set()
                recorded_response = response_record if response_record and round_no == 1 and participant["id"] in recorded_ids else None
                if record_events:
                    event_specs.append(
                        {
                            "round_no": round_no,
                            "participant_id": participant["id"],
                            "event_type": "action",
                            "action": action,
                            "state": action_state,
                            "repair": repair,
                            "recorded_response": recorded_response,
                        }
                    )

            state_after = cls._ledger_snapshot(participants, counterparty, price_after)
            round_record = {
                "round": round_no,
                "price_before": q(price_before),
                "price": q(price_after),
                "price_transition": transition_record,
                "state_before": state_before,
                "actions": actions,
                "state_after": state_after,
                # Existing clients used ``state`` as the round state; retain
                # that alias while exposing the explicit before/after states.
                "state": state_after,
                "explanation": "Exogenous declared shock/seeded drift followed by bounded participant rules; no market price discovery was used.",
            }
            rounds.append(round_record)
            previous_price = price_after
            # Let a queued provider or test task yield between deterministic
            # rounds without introducing any state mutation.

        final_state = cls._ledger_snapshot(participants, counterparty, previous_price)
        return {
            "rounds": rounds,
            "participants": cls._final_participants(participants, previous_price),
            "final_state": final_state,
            "event_specs": event_specs,
        }

