    @staticmethod
    def _rounds_from_events(events: list[Any]) -> list[dict[str, Any]]:
        by_round: dict[int, dict[str, Any]] = {}
        for event in events:
            round_no = int(event["round_no"])
            if round_no <= 0:
                continue
            record = by_round.setdefault(round_no, {"round": round_no, "price": None, "actions": [], "explanation": "Recorded round; simulation is still in progress."})
            action = json_loads(event["action_json"], {})
            state = json_loads(event["state_json"], {})
            if event["event_type"] == "price_transition":
                record["price"] = action.get("price_after")
                record["price_transition"] = action
                record["state_after_price"] = state.get("state")
            elif event["event_type"] == "action":
                record["actions"].append(action)
                record["state"] = state.get("state")
        return [by_round[key] for key in sorted(by_round)]

