    @staticmethod
    def _model_prompt(
        question: str,
        horizon: str,
        participants: list[dict[str, Any]],
        source_snapshots: list[dict[str, Any]],
        initial_price: str,
        shock_percent: str,
    ) -> str:
        # Only shock-informed participants receive the optional hosted
        # interpretation.  Delayed participants are intentionally absent
        # from this packet and remain governed by the deterministic rules,
        # preventing the model from inferring a withheld price/shock.
        selected = [item for item in participants if item.get("information_mode") == "shock_informed"][:2]
        try:
            opening = d(initial_price)
            shock = d(shock_percent)
            post_shock = (opening * (ONE + shock / Decimal("100"))).quantize(Q, rounding=ROUND_HALF_UP)
        except ValueError:
            opening = ZERO
            post_shock = ZERO
        packet = {
            "question": question,
            "horizon": horizon,
            "round": 1,
            "participants": [
                {
                    "id": item["id"],
                    "horizon": item["horizon"],
                    "style": item["style"],
                    "information_set": item["information_set"],
                    "initial_cash": item["initial_cash"],
                    "initial_shares": item["initial_shares"],
                    "initial_nav": item.get("nav", item["initial_cash"]),
                    "adjustment_speed": item["adjustment_speed"],
                    "max_long_exposure": item["max_long_exposure"],
                    "observable_round_one": (
                        {
                            "price_before": q(opening),
                            "price_after": q(post_shock),
                            "shock_percent": q(d(shock_percent)),
                            "shock_visible": True,
                        }
                        if item.get("information_mode") == "shock_informed"
                        else {
                            "price_before": q(opening),
                            "price_after": q(opening),
                            "shock_percent": None,
                            "shock_visible": False,
                            "hidden_information": "The declared shock and post-shock price are not observable to this participant in round one.",
                        }
                    ),
                }
                for item in selected
            ],
            "sources": [
                {
                    "id": source["id"],
                    "namespace": source["namespace"],
                    "title": source.get("title"),
                    "url": source.get("url"),
                    "publication_at": source.get("publication_at"),
                    "observed_at": source.get("observed_at"),
                    "retrieved_at": source.get("retrieved_at"),
                    "version": source["version"],
                    "content_hash": source["content_hash"],
                    "locator": source["locator"],
                    "content_excerpt": source["content"][:12_000],
                }
                for source in source_snapshots
            ],
        }
        return (
            "You are the bounded A07 simulation analyst. Return exactly one JSON object matching the supplied schema, "
            "with exactly one action for each listed participant. Choose only buy, sell, or hold and a "
            "target_weight from 0 through 0.25. The backend owns prices, cash, shares, NAV, trade quantity, and all "
            "arithmetic. Do not provide reasoning or transcripts.\n\n"
            + json.dumps(packet, ensure_ascii=False, sort_keys=True)
        )

    @staticmethod
    async def _maybe_await(value: Any) -> Any:
        return await value if inspect.isawaitable(value) else value

    async def _preflight(self, registry: Any, adapter: Any, config: ModelConfig) -> dict[str, Any] | None:
        method = getattr(registry, "preflight", None)
        if callable(method):
            result = await self._maybe_await(method(config, False))
        else:
            method = getattr(adapter, "preflight", None)
            if not callable(method):
                raise ProviderError("capability", "Configured provider has no supported subscription preflight.")
            result = await self._maybe_await(method(config, False))
        if result is False:
            raise ProviderError("unavailable", "Configured provider preflight failed.")
        if isinstance(result, Mapping) and result.get("available") is False:
            kind = str(result.get("status") or "unavailable")
            reason = str(result.get("reason") or "Configured provider preflight failed.")
            raise ProviderError(kind, reason)
        if getattr(result, "available", True) is False:
            raise ProviderError(str(getattr(result, "status", "unavailable")), str(getattr(result, "reason", None) or "Configured provider preflight failed."))
        return dict(result) if isinstance(result, Mapping) else None

    @asynccontextmanager
    async def _generation_slot(self, registry: Any, provider: str):
        method = getattr(registry, "generation_slot", None)
        if not callable(method):
            yield
            return
        context = method(provider)
        if inspect.isawaitable(context):
            context = await context
        async with context:
            yield

    @staticmethod
    def _adapter(registry: Any, config: ModelConfig) -> Any:
        method = getattr(registry, "adapter", None)
        if callable(method):
            return method(config.provider)
        if callable(getattr(registry, "execute", None)):
            return registry
        raise ProviderError("unsupported_provider", "Configured provider registry cannot resolve an adapter.")

    async def _call_model(
        self,
        simulation_id: str,
        config: ModelConfig,
        prompt: str,
        schema: dict[str, Any],
    ) -> tuple[dict[str, Any], dict[str, Any] | None]:
        registry = self._provider_registry()
        adapter = self._adapter(registry, config)
        await self._preflight(registry, adapter, config)
        workroot = getattr(getattr(self.repository, "config", None), "data_dir", Path("/tmp"))
        workdir = Path(workroot) / "workers" / f"simulation-{simulation_id}"
        workdir.mkdir(parents=True, exist_ok=True)
        attempt_id = f"{simulation_id}:round1"
        async with self._generation_slot(registry, config.provider):
            # This is the sole configured-provider generation for a run.
            exact_preflight = getattr(adapter, "is_preflighted", None)
            if callable(exact_preflight) and not exact_preflight(config):
                method = getattr(registry, "preflight", None)
                if callable(method):
                    probe = await self._maybe_await(method(config, True))
                else:
                    probe = await self._maybe_await(adapter.preflight(config, True))
                if isinstance(probe, Mapping) and (probe.get("available") is False or probe.get("actual_execution") is not True):
                    raise ProviderError(str(probe.get("status") or "capability"), str(probe.get("reason") or "Configured provider schema preflight failed."))
            result = await self._maybe_await(adapter.execute(attempt_id, prompt, config, schema, workdir, None))
        if isinstance(result, ProviderResult):
            if not result.actual_execution:
                raise ProviderError("execution", "Configured provider did not execute the simulation generation.")
            payload = result.payload
            usage = result.usage
        elif hasattr(result, "payload"):
            if getattr(result, "actual_execution", True) is False:
                raise ProviderError("execution", "Configured provider did not execute the simulation generation.")
            payload = getattr(result, "payload")
            usage = getattr(result, "usage", None)
        elif isinstance(result, Mapping) and "payload" in result and isinstance(result.get("payload"), Mapping):
            payload = dict(result["payload"])
            usage = result.get("usage") if isinstance(result.get("usage"), Mapping) else None
        elif isinstance(result, Mapping):
            payload = dict(result)
            usage = None
        else:
            raise ProviderError("invalid_output", "Configured provider returned a non-object structured response.")
        if not isinstance(payload, dict):
            raise ProviderError("invalid_output", "Configured provider returned an invalid structured response.")
        return payload, dict(usage) if isinstance(usage, Mapping) else None

    @staticmethod
    def _validate_model_response(payload: Any, participant_ids: list[str]) -> tuple[dict[str, dict[str, Any]], dict[str, Any]]:
        validation_ids = list(participant_ids)
        decisions: dict[str, dict[str, Any]] = {}
        repairs: list[dict[str, Any]] = []
        errors: list[str] = []
        by_id: dict[str, Any] = {}
        top_level_valid = (
            isinstance(payload, Mapping)
            and set(payload.keys()) == {"actions"}
            and isinstance(payload.get("actions"), list)
            and len(payload["actions"]) == len(validation_ids)
        )
        if not top_level_valid:
            errors.append(f"response must contain exactly {len(validation_ids)} actions")
        else:
            for index, item in enumerate(payload["actions"]):
                if not isinstance(item, Mapping):
                    errors.append(f"action {index + 1} is not an object")
                    continue
                participant_id = item.get("participant_id")
                if participant_id not in validation_ids:
                    errors.append(f"action {index + 1} has an unknown participant_id")
                    continue
                if participant_id in by_id:
                    errors.append(f"participant {participant_id} has duplicate actions")
                    continue
                by_id[str(participant_id)] = dict(item)

        for participant_id in validation_ids:
            item = by_id.get(participant_id)
            reason: str | None = None
            action: Any = None
            target_value: Decimal | None = None
            if item is None:
                reason = "missing participant action"
            else:
                action = item.get("action")
                if set(item.keys()) != {"participant_id", "action", "target_weight"}:
                    reason = "action contains unsupported fields"
                elif action not in ACTION_VALUES:
                    reason = "action must be buy, sell, or hold"
                elif not isinstance(item.get("target_weight"), str):
                    reason = "target_weight must be a decimal string"
                else:
                    try:
                        target_value = d(item.get("target_weight"))
                    except ValueError:
                        reason = reason or "target_weight is not a finite decimal"
                    if target_value is not None and not ZERO <= target_value <= MAX_LONG_EXPOSURE:
                        reason = reason or "target_weight exceeds the maximum long exposure of 0.25"
            if reason is not None or not top_level_valid:
                if reason is None:
                    reason = "response shape is invalid"
                errors.append(f"{participant_id}: {reason}")
                repairs.append(
                    {
                        "participant_id": participant_id,
                        "reason": reason,
                        "requested_action": action,
                        "requested_target_weight": q(target_value) if target_value is not None else item.get("target_weight") if item else None,
                        "applied_action": "hold",
                        "applied_quantity": q(ZERO),
                        "deterministic": True,
                    }
                )
                decisions[participant_id] = {
                    "valid": False,
                    "repair": repairs[-1],
                }
            else:
                decisions[participant_id] = {"valid": True, "action": action, "target_weight": q(target_value), "target_decimal": target_value}

        return decisions, {
            "round": 1,
            "participant_ids": validation_ids,
            "response": _retain_structured_response(payload),
            "validated_actions": [
                {"participant_id": participant_id, "action": item["action"], "target_weight": item["target_weight"]}
                for participant_id, item in decisions.items()
                if item.get("valid")
            ],
            "repairs": repairs,
            "validation_errors": errors,
        }

    @staticmethod
    def _model_decision_map(decisions: Mapping[str, dict[str, Any]], controlled_ids: set[str] | None = None) -> dict[str, dict[str, Any]]:
        result: dict[str, dict[str, Any]] = {}
        for participant_id, item in decisions.items():
            if item.get("valid"):
                if controlled_ids is None or participant_id in controlled_ids:
                    result[participant_id] = {
                        "valid": True,
                        "action": item["action"],
                        "target_weight": item["target_weight"],
                    }
            else:
                # Invalid output is a deterministic no-op.  A valid delayed
                # action is filtered above and therefore cannot influence the
                # ledger.
                result[participant_id] = {"valid": False, "repair": item.get("repair")}
        return result

